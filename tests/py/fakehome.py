"""A throwaway HOME for the tests, so nothing ever touches the real one.

FakeHome builds a temporary directory that looks like a user's home: the four
XDG folders exist, env() gives a subprocess environment in which HOME and
XDG_* point inside it (and nothing points at the real home), and a few
generators lay out what browserglass.py reads: Firefox-like profile roots and
profiles.ini, profiles of the new profile manager's Profile Groups (on disk
but absent from profiles.ini), niri KDL files and DMS's dms-colors.json.

    with FakeHome() as fh:
        fh.make_profile(".mozilla/firefox", "abc.default", prefs={"a.b": True})
        fh.write_profiles_ini(".mozilla/firefox", [{"name": "default", "path": "abc.default"}])
        proc = fh.run_script(["status", "--json"])

Python stdlib only, runs on Python >= 3.9.
"""

import json
import os
import pwd
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "browserglass.py"

# The account's real home, from the password database: $HOME may already be
# faked by whoever runs the tests, the password database is not.
REAL_HOME = Path(pwd.getpwuid(os.getuid()).pw_dir).resolve()

PREFS_HEADER = (
    "// Mozilla User Preferences\n"
    "\n"
    "// DO NOT EDIT THIS FILE.\n"
    "//\n"
    "// If you make changes to this file while the application is running,\n"
    "// the changes will be overwritten when the application exits.\n"
    "\n"
)


def _within(path, parent):
    """True when `path` is `parent` or lies below it (both resolved)."""
    path = Path(path)
    parent = Path(parent)
    return path == parent or parent in path.parents


def _temp_base():
    """A temp directory outside the real home, or an error.

    tempfile.gettempdir() honours $TMPDIR; when that points inside the real
    home the fake home would carry a real-home prefix, so fall back to the
    system's own temp folders instead.
    """
    candidates = [tempfile.gettempdir(), "/tmp", "/var/tmp"]
    for candidate in candidates:
        base = Path(candidate).resolve()
        if base.is_dir() and os.access(str(base), os.W_OK) and not _within(base, REAL_HOME):
            return base
    raise RuntimeError("no writable temp directory outside the real home")


def pref_value(value):
    """A Python value written the way prefs.js writes it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    raise TypeError("unsupported pref value: %r" % (value,))


def prefs_js(prefs):
    """The text of a prefs.js holding `prefs` (a dict), in Firefox's layout."""
    lines = ['user_pref("%s", %s);\n' % (key, pref_value(value)) for key, value in sorted(prefs.items())]
    return PREFS_HEADER + "".join(lines)


class FakeHome:
    """A temporary home directory with its XDG folders.

    Use it as a context manager, or call cleanup() yourself. `name` is the
    fake account name and the home folder's basename (a report test can check
    it never appears in the output).
    """

    def __init__(self, name="alice"):
        self._tmp = tempfile.TemporaryDirectory(prefix="bg-fakehome-", dir=str(_temp_base()))
        self.root = Path(self._tmp.name).resolve()
        self.name = name
        self.home = self.root / name
        self.config = self.home / ".config"
        self.state = self.home / ".local" / "state"
        self.cache = self.home / ".cache"
        self.data = self.home / ".local" / "share"
        self.tmp = self.root / "tmp"
        self.runtime = self.root / "run"
        for folder in (self.home, self.config, self.state, self.cache, self.data, self.tmp):
            folder.mkdir(parents=True, exist_ok=True)
        self.runtime.mkdir(mode=0o700, exist_ok=True)
        self.assert_safe()

    # -- lifetime -----------------------------------------------------------

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.cleanup()
        return False

    def cleanup(self):
        # Make read-only folders writable again so the tree can go
        for dirpath, dirnames, _ in os.walk(str(self.root)):
            for d in dirnames:
                p = os.path.join(dirpath, d)
                if not os.path.islink(p):
                    os.chmod(p, 0o700)
        self._tmp.cleanup()

    # -- safety -------------------------------------------------------------

    def assert_safe(self):
        """Refuse to go on unless the fake home is a temp folder, far from the real one."""
        base = Path(tempfile.gettempdir()).resolve()
        system_temps = [base, Path("/tmp").resolve(), Path("/var/tmp").resolve()]
        if not any(_within(self.home, t) for t in system_temps):
            raise AssertionError("fake HOME %s is not under a system temp dir" % self.home)
        if _within(self.home, REAL_HOME) or _within(REAL_HOME, self.home):
            raise AssertionError("fake HOME %s overlaps the real home" % self.home)

    def resolve(self, rel):
        """`rel` (relative to the fake home, or absolute inside it) as an absolute Path.

        Raises ValueError for a path that escapes the fake home.
        """
        path = Path(rel)
        if not path.is_absolute():
            path = self.home / path
        normal = Path(os.path.normpath(str(path)))
        if not _within(normal, self.root):
            raise ValueError("path escapes the fake home: %s" % rel)
        return normal

    # -- environment --------------------------------------------------------

    def env(self, extra=None):
        """A complete environment for a subprocess, built from scratch.

        HOME, USER, XDG_* and TMPDIR point inside the fake home. Only PATH is
        inherited, minus any entry inside the real home. `extra` (a dict) is
        applied last; a value of None removes the variable.
        """
        path_entries = [
            p for p in os.environ.get("PATH", "/usr/local/bin:/usr/bin:/bin").split(os.pathsep)
            if os.path.isabs(p)
            and not _within(Path(os.path.normpath(p)), REAL_HOME)
            and not _within(Path(os.path.realpath(p)), REAL_HOME)
        ]
        env = {
            "PATH": os.pathsep.join(path_entries) or "/usr/bin:/bin",
            "HOME": str(self.home),
            "USER": self.name,
            "LOGNAME": self.name,
            "XDG_CONFIG_HOME": str(self.config),
            "XDG_STATE_HOME": str(self.state),
            "XDG_CACHE_HOME": str(self.cache),
            "XDG_DATA_HOME": str(self.data),
            "XDG_RUNTIME_DIR": str(self.runtime),
            "TMPDIR": str(self.tmp),
            # No real Firefox build decides a never-run profile's channel.
            "BG_FIREFOX_BUILDS": str(self.root / "usr" / "lib64" / "firefox"),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
            "PYTHONDONTWRITEBYTECODE": "1",
        }
        for key, value in (extra or {}).items():
            if value is None:
                env.pop(key, None)
            else:
                env[key] = str(value)
        return env

    def leaks(self, env=None):
        """The variables of `env` (default env()) whose value names the real home."""
        env = self.env() if env is None else env
        real = str(REAL_HOME)
        found = []
        for key, value in env.items():
            for part in str(value).split(os.pathsep):
                if part == real or part.startswith(real + "/"):
                    found.append(key)
                    break
        return found

    # -- files --------------------------------------------------------------

    def write(self, rel, content, mode=None):
        """Write `content` (str or bytes) at `rel`, creating parents. Returns the Path."""
        path = self.resolve(rel)
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            with open(str(path), "w", encoding="utf-8", newline="") as f:
                f.write(content)
        if mode is not None:
            os.chmod(str(path), mode)
        return path

    def read(self, rel):
        return self.resolve(rel).read_text(encoding="utf-8")

    def exists(self, rel):
        return os.path.lexists(str(self.resolve(rel)))

    def snapshot(self, rel="."):
        """Everything below `rel`: {relative path: (kind, mode, content)}.

        kind is "dir", "file" or "link"; content is the bytes of a file, the
        target of a link, None for a folder. Two snapshots compare equal when
        the trees are identical byte for byte, permissions included.
        """
        top = self.resolve(rel)
        result = {}
        for dirpath, dirnames, filenames in os.walk(str(top)):
            dirnames.sort()
            for name in sorted(dirnames + filenames):
                full = os.path.join(dirpath, name)
                key = os.path.relpath(full, str(top))
                st = os.lstat(full)
                mode = stat.S_IMODE(st.st_mode)
                if stat.S_ISLNK(st.st_mode):
                    result[key] = ("link", mode, os.readlink(full))
                elif stat.S_ISDIR(st.st_mode):
                    result[key] = ("dir", mode, None)
                else:
                    with open(full, "rb") as f:
                        result[key] = ("file", mode, f.read())
        return result

    # -- generators ---------------------------------------------------------

    def make_profile(self, root_rel, name, files=None, prefs=None):
        """A profile folder `root_rel/name` with a prefs.js. Returns its Path.

        `prefs` (dict) fills prefs.js; `files` maps a path inside the profile
        (e.g. "chrome/userChrome.css", "user.js") to its str or bytes content.
        """
        profile = self.resolve(Path(root_rel) / name)
        profile.mkdir(parents=True, exist_ok=True)
        self.write(profile / "prefs.js", prefs_js(prefs or {}))
        for rel, content in (files or {}).items():
            self.write(profile / rel, content)
        return profile

    def write_profiles_ini(self, root_rel, profiles=(), installs=None, relative=True, general=True):
        """profiles.ini under `root_rel`. Returns its Path.

        `profiles` is a list of names or of dicts with "name", optional
        "path" (defaults to the name, relative to the root), optional
        "default" (bool) and optional "relative" (overrides `relative`).
        A non-relative profile gets its absolute path. `installs` maps an
        install hash to the profile path its Default= names, written the way
        the profile itself is.
        """
        root = self.resolve(root_rel)
        lines = []
        entries = []
        for item in profiles:
            if isinstance(item, str):
                item = {"name": item}
            path = item.get("path", item["name"])
            is_rel = item.get("relative", relative)
            entries.append((item, path, is_rel))

        def written(path, is_rel):
            return path if is_rel else str(root / path)

        rel_by_path = {path: is_rel for _, path, is_rel in entries}
        for install_hash, path in (installs or {}).items():
            lines.append("[Install%s]" % install_hash)
            lines.append("Default=%s" % written(path, rel_by_path.get(path, relative)))
            lines.append("Locked=1")
            lines.append("")
        for index, (item, path, is_rel) in enumerate(entries):
            lines.append("[Profile%d]" % index)
            lines.append("Name=%s" % item["name"])
            lines.append("IsRelative=%d" % (1 if is_rel else 0))
            lines.append("Path=%s" % written(path, is_rel))
            if item.get("default"):
                lines.append("Default=1")
            lines.append("")
        if general:
            lines.append("[General]")
            lines.append("StartWithLastProfile=1")
            lines.append("Version=2")
            lines.append("")
        return self.write(root / "profiles.ini", "\n".join(lines))

    def make_profile_group(self, root_rel, names, group_id="0a1b2c3d4e5f", prefs=None, files=None):
        """Profiles of the new profile manager: folders with a prefs.js under
        the root, absent from profiles.ini, plus the group's database file
        (an empty placeholder) in "Profile Groups/". Returns the profile Paths.
        """
        made = [self.make_profile(root_rel, name, files=files, prefs=prefs) for name in names]
        self.write(Path(root_rel) / "Profile Groups" / ("%s.sqlite" % group_id), b"")
        return made

    def write_kdl(self, path, text):
        """A KDL file at `path` (relative to the fake home). Returns its Path."""
        return self.write(path, text)

    def write_dms_colors(self, mode="dark", surface_dark="#101418", surface_light="#f7f9ff"):
        """$XDG_CACHE_HOME/dms/dms-colors.json, shaped like DMS's (keys dank16,
        mode, colors.dark, colors.light) with made-up colours. Returns its Path.
        """
        def palette(surface, on_surface, primary):
            return {
                "background": surface,
                "on_background": on_surface,
                "on_surface": on_surface,
                "primary": primary,
                "surface": surface,
                "surface_container": surface,
                "surface_container_high": surface,
                "surface_variant": surface,
            }

        doc = {
            "dank16": {
                "color0": {"dark": surface_dark, "light": surface_light, "default": surface_dark},
                "color7": {"dark": "#e0e0e0", "light": "#202020", "default": "#e0e0e0"},
            },
            "mode": mode,
            "colors": {
                "dark": palette(surface_dark, "#e0e0e0", "#a0c4ff"),
                "light": palette(surface_light, "#202020", "#3050a0"),
            },
        }
        return self.write(self.cache / "dms" / "dms-colors.json", json.dumps(doc, indent=4) + "\n")

    # -- running the script -------------------------------------------------

    def run_script(self, args, stdin=None, script=None, extra_env=None, timeout=60, cwd=None):
        """Run `python3 -I <repo>/browserglass.py args...` inside the fake home.

        Uses env() (plus `extra_env`), the fake home (or `cwd`) as working directory and
        the interpreter running the tests. Returns the CompletedProcess with
        text stdout and stderr; never raises on a nonzero exit.
        """
        script = SCRIPT if script is None else Path(script)
        argv = [sys.executable or shutil.which("python3") or "python3", "-I", str(script)]
        argv += [str(a) for a in args]
        return subprocess.run(
            argv,
            input=stdin,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
            env=self.env(extra_env),
            cwd=str(self.home) if cwd is None else str(cwd),
            timeout=timeout,
        )


# -- the script as a module -------------------------------------------------

FIXTURES = Path(__file__).resolve().parent / "fixtures"
_SCRIPT_MODULE = None


def load_script():
    """browserglass.py imported as a module (once, without writing bytecode),
    for unit tests of its functions. Every function that reads the
    environment takes an `env` argument: pass FakeHome.env(), never rely on
    os.environ.
    """
    global _SCRIPT_MODULE
    if _SCRIPT_MODULE is None:
        import importlib.util
        old = sys.dont_write_bytecode
        sys.dont_write_bytecode = True
        try:
            spec = importlib.util.spec_from_file_location("browserglass_under_test", str(SCRIPT))
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
        finally:
            sys.dont_write_bytecode = old
        _SCRIPT_MODULE = module
    return _SCRIPT_MODULE


def fixture_text(rel, **subst):
    """Text of tests/py/fixtures/`rel`, with every "@KEY@" replaced by subst[KEY]."""
    text = (FIXTURES / rel).read_text(encoding="utf-8")
    for key, value in subst.items():
        text = text.replace("@%s@" % key, str(value))
    return text


# -- golden files -----------------------------------------------------------

GOLDEN = Path(__file__).resolve().parent / "golden"
# BG_REGEN_GOLDEN=1 rewrites the golden files from the current output instead
# of comparing (then review the diff with git before keeping it).
REGEN_GOLDEN = os.environ.get("BG_REGEN_GOLDEN") == "1"
_GOLDEN_MARK = "@@@@ "


def dump_golden(results):
    """Text of a golden file for `results` ({case: output text}, ordered).

    Cases sharing the same output are grouped: each distinct output is
    written once, after the list of the cases that produce it:
        @@@@ cases
        <case>
        @@@@ text
        <output, verbatim>
        @@@@ end
    """
    groups = []
    index = {}
    for case, text in results.items():
        if text not in index:
            index[text] = len(groups)
            groups.append((text, []))
        groups[index[text]][1].append(case)
    out = []
    for text, cases in groups:
        if any(line.startswith(_GOLDEN_MARK) for line in text.split("\n")):
            raise ValueError("output contains a golden marker line")
        out.append(_GOLDEN_MARK + "cases\n")
        out.extend(case + "\n" for case in cases)
        out.append(_GOLDEN_MARK + "text\n")
        out.append(text)
        if not text.endswith("\n"):
            out.append("\n" + _GOLDEN_MARK + "no-newline-at-end\n")
        out.append(_GOLDEN_MARK + "end\n")
    return "".join(out)


def load_golden(text):
    """{case: output text} from a golden file's text (see dump_golden)."""
    results = {}
    lines = text.split("\n")
    i = 0
    while i < len(lines) and lines[i] == "":
        i += 1
    while i < len(lines):
        if lines[i] == "":
            i += 1
            continue
        if lines[i] != _GOLDEN_MARK + "cases":
            raise ValueError("golden line %d: expected '@@@@ cases'" % (i + 1))
        i += 1
        cases = []
        while lines[i] != _GOLDEN_MARK + "text":
            cases.append(lines[i])
            i += 1
        i += 1
        body = []
        while lines[i] not in (_GOLDEN_MARK + "end", _GOLDEN_MARK + "no-newline-at-end"):
            body.append(lines[i])
            i += 1
        if lines[i] == _GOLDEN_MARK + "no-newline-at-end":
            output = "\n".join(body)
            i += 1
        else:
            output = "".join(line + "\n" for line in body)
        i += 1
        for case in cases:
            results[case] = output
    return results


def check_golden(test, name, results):
    """Compare `results` ({case: output}) with tests/py/golden/`name`, or
    rewrite that file when BG_REGEN_GOLDEN=1."""
    path = GOLDEN / name
    if REGEN_GOLDEN:
        GOLDEN.mkdir(parents=True, exist_ok=True)
        with open(str(path), "w", encoding="utf-8", newline="") as f:
            f.write(dump_golden(results))
        return
    if not path.exists():
        test.fail("missing golden file %s: run with BG_REGEN_GOLDEN=1" % name)
    expected = load_golden(path.read_text(encoding="utf-8"))
    test.assertEqual(sorted(expected), sorted(results), "%s: the set of cases changed" % name)
    for case in results:
        if results[case] != expected[case]:
            test.assertEqual(results[case], expected[case], "%s: case %s" % (name, case))


# -- locks and detached children ----------------------------------------------

# A child holding a lock on argv[1] until it reads a line on stdin.
# argv[2]: "posix" (fcntl record lock, as Firefox holds .parentlock) or
# "flock" (as browserglass.py holds state.lock).
_HOLDER = r"""
import fcntl, os, sys
fd = os.open(sys.argv[1], os.O_RDWR | os.O_CREAT, 0o644)
if sys.argv[2] == "flock":
    fcntl.flock(fd, fcntl.LOCK_EX)
else:
    fcntl.lockf(fd, fcntl.LOCK_EX)
print("ready", flush=True)
sys.stdin.readline()
os.close(fd)
print("released", flush=True)
sys.stdin.readline()
"""


class LockHolder:
    """A process holding a lock on `path` (inside the fake home) while alive.

        with LockHolder(fh, profile / ".parentlock") as holder:
            ...            # the profile looks like a running browser
            holder.release()
    """

    def __init__(self, fh, path, kind="posix", timeout=10):
        self.fh = fh
        self.path = fh.resolve(path)
        self.child = subprocess.Popen(
            [sys.executable or "python3", "-I", "-c", _HOLDER, str(self.path), kind],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, universal_newlines=True,
            env=fh.env(), cwd=str(fh.home))
        self._expect("ready", timeout)

    def _expect(self, word, timeout):
        import select
        ready, _, _ = select.select([self.child.stdout], [], [], timeout)
        line = self.child.stdout.readline().strip() if ready else ""
        if line != word:
            self.stop()
            raise AssertionError("lock holder did not say %r (got %r)" % (word, line))

    def release(self, timeout=10):
        if self.child.poll() is None:
            self.child.stdin.write("\n")
            self.child.stdin.flush()
            self._expect("released", timeout)

    def stop(self):
        if self.child.poll() is None:
            self.child.kill()
        self.child.wait(10)
        for stream in (self.child.stdin, self.child.stdout):
            if stream:
                stream.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.stop()
        return False


def fake_home_pids(fh):
    """PIDs (not ours) whose environment has HOME set to this fake home:
    what our subprocesses left behind, detached children included."""
    wanted = ("HOME=" + str(fh.home)).encode()
    found = []
    for name in os.listdir("/proc"):
        if not name.isdigit() or int(name) == os.getpid():
            continue
        try:
            with open("/proc/%s/environ" % name, "rb") as f:
                if wanted in f.read().split(b"\0"):
                    found.append(int(name))
        except OSError:
            continue
    return found


def kill_strays(fh):
    """SIGKILL every process left behind inside this fake home."""
    import signal
    for pid in fake_home_pids(fh):
        try:
            os.kill(pid, signal.SIGKILL)
        except OSError:
            pass


def wait_until(predicate, timeout=10.0, step=0.02):
    """Poll `predicate` until true or `timeout` seconds; returns its last value."""
    import time
    deadline = time.monotonic() + timeout
    while True:
        value = predicate()
        if value or time.monotonic() >= deadline:
            return value
        time.sleep(step)
